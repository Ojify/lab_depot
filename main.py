# Проверка возможности выдачи оборудования
from datetime import datetime, date

# Текущая дата для проверки срока возврата
today = date.today()

# Ввод данных пользователем
inventory_num = int(input("Введите инвентарный номер оборудования: "))
status = input("Введите состояние оборудования (исправно/в ремонте/выдано): ")
return_date_str = input("Введите планируемую дату возврата (ГГГГ-ММ-ДД): ")

# Преобразуем строку с датой в объект date
try:
    return_date = datetime.strptime(return_date_str, "%Y-%m-%d").date()
except ValueError:
    print("Ошибка: неверный формат даты. Используйте ГГГГ-ММ-ДД.")
    exit()

# Анализ доступности
if status == "в ремонте":
    print(f"Оборудование {inventory_num} находится в ремонте – выдача невозможна.")
elif status == "выдано":
    print(f"Оборудование {inventory_num} уже выдано другому сотруднику.")
elif status == "исправно":
    if return_date >= today:
        print(f"Оборудование {inventory_num} доступно для выдачи до {return_date}.")
    else:
        print("Ошибка: дата возврата не может быть раньше сегодняшнего дня.")
else:
    print("Неизвестное состояние оборудования. Допустимые значения: исправно, в ремонте, выдано.")